export type FontName = '5x7' | '3x5';

/** Rasterise text to a list of [x, y] pixel coordinates (y down), plus its size. */
export function rasterText(text: string, font: FontName, spacing = 1): { pixels: [number, number][]; width: number; height: number } {
  const glyphs = font === '5x7' ? FONT_5x7 : FONT_3x5;
  const gh = font === '5x7' ? 7 : 5;
  const pixels: [number, number][] = [];
  let x = 0;
  for (const ch of text.toUpperCase()) {
    const glyph = glyphs[ch];
    if (!glyph) throw new Error(`Glyph "${ch}" missing from ${font} font`);
    const gw = glyph[0].length; // glyphs may be wider than the nominal size
    glyph.forEach((row, y) => {
      for (let i = 0; i < gw; i++) if (row[i] === '#') pixels.push([x + i, y]);
    });
    x += gw + spacing;
  }
  return { pixels, width: x - spacing, height: gh };
}
